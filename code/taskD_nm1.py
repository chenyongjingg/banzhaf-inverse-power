"""Check: do all known solutions have all (n-1)-sets winning? And is c even?"""
from math import gcd
from functools import reduce

def check_nm1(antichain, n):
    # is every (n-1)-set winning?
    ac=set(antichain)
    def win(m): return any((m&c)==c for c in ac)
    full=(1<<n)-1
    for x in range(n):
        nm1 = full & ~(1<<x)
        if not win(nm1): return False
    return True

def swings_brute(ac, n):
    def win(m): return any((m&c)==c for c in ac)
    eta=[0]*n
    for i in range(n):
        bit=1<<i
        for m in range(1<<n):
            if m&bit: continue
            if (not win(m)) and win(m|bit): eta[i]+=1
    return eta

# closed-form complement-of-edge solutions
import networkx as nx
def comp_edge_check(n, d):
    num=d*(2*n-8)+4*(n-1)
    if num%7: return None
    c=num//7; ds=d+c//2
    seq=[d]*(n-1)+[ds]
    if not nx.is_graphical(seq): return None
    G=nx.havel_hakimi_graph(seq)
    ac=[((1<<n)-1)&~((1<<u)|(1<<v)) for u,v in G.edges()]
    return ac, c, check_nm1(ac, n)

