"""Check if MILP solutions fit the threshold family (all |S|>=n-1 winning)."""
from collections import Counter

def check(n, antichain):
    full=set()
    for c in antichain:
        c=set(c)
        for m in range(1<<n):
            S=frozenset(j for j in range(n) if (m>>j)&1)
            if c<=S: full.add(S)
    sizes=Counter(len(s) for s in full)
    n1_win=len([s for s in full if len(s)==n-1])
    print(f"n={n}: winning sizes={dict(sizes)}, (n-1)-sets winning {n1_win}/{n}")

